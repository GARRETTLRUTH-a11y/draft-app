/**
 * Small, dependency-free ZIP writer. Files use "stored" (uncompressed)
 * ZIP entries so image bytes are preserved exactly and the browser does
 * not have to re-encode already-compressed JPEG/PNG/GIF files.
 *
 * ZIP32 requires <4 GiB total and <65535 entries. The export page applies
 * substantially lower limits to protect browser memory.
 */
type Entry = { path: string; data: ArrayBuffer };

const CRC_TABLE = new Uint32Array(256);
for (let i = 0; i < 256; i++) {
  let value = i;
  for (let bit = 0; bit < 8; bit++) {
    value = value & 1 ? 0xedb88320 ^ (value >>> 1) : value >>> 1;
  }
  CRC_TABLE[i] = value >>> 0;
}

function crc32(data: ArrayBuffer): number {
  const bytes = new Uint8Array(data);
  let crc = 0xffffffff;
  for (const byte of bytes) {
    crc = CRC_TABLE[(crc ^ byte) & 0xff] ^ (crc >>> 8);
  }
  return (crc ^ 0xffffffff) >>> 0;
}

export function makeZip(entries: Entry[]): Blob {
  if (!entries.length || entries.length > 65535) {
    throw new Error("ZIP file count is outside supported limits.");
  }

  const chunks: BlobPart[] = [];
  const central: Uint8Array<ArrayBuffer>[] = [];
  const encoder = new TextEncoder();
  let localOffset = 0;
  let centralBytes = 0;

  for (const entry of entries) {
    // Names are generated by the caller; do not include user-controlled paths.
    if (!entry.path || entry.path.startsWith("/") || entry.path.includes("..")) {
      throw new Error("Invalid ZIP entry path.");
    }
    const filename = encoder.encode(entry.path);
    if (filename.byteLength > 65535) throw new Error("ZIP filename is too long.");
    const length = entry.data.byteLength;
    const checksum = crc32(entry.data);

    const local = new Uint8Array(30 + filename.byteLength);
    const l = new DataView(local.buffer);
    l.setUint32(0, 0x04034b50, true);
    l.setUint16(4, 20, true);
    l.setUint16(6, 0x0800, true); // UTF-8 paths
    l.setUint16(8, 0, true); // stored
    l.setUint16(10, 0, true);
    l.setUint16(12, 33, true); // 1980-01-01
    l.setUint32(14, checksum, true);
    l.setUint32(18, length, true);
    l.setUint32(22, length, true);
    l.setUint16(26, filename.byteLength, true);
    local.set(filename, 30);
    chunks.push(local, entry.data);

    const directory = new Uint8Array(46 + filename.byteLength);
    const d = new DataView(directory.buffer);
    d.setUint32(0, 0x02014b50, true);
    d.setUint16(4, 20, true);
    d.setUint16(6, 20, true);
    d.setUint16(8, 0x0800, true);
    d.setUint16(10, 0, true);
    d.setUint16(12, 0, true);
    d.setUint16(14, 33, true);
    d.setUint32(16, checksum, true);
    d.setUint32(20, length, true);
    d.setUint32(24, length, true);
    d.setUint16(28, filename.byteLength, true);
    d.setUint32(42, localOffset, true);
    directory.set(filename, 46);
    central.push(directory);
    centralBytes += directory.byteLength;
    localOffset += local.byteLength + length;
    if (localOffset + centralBytes > 0xffffffff) {
      throw new Error("ZIP exceeds its 4 GB size limit.");
    }
  }

  chunks.push(...central);
  const end = new Uint8Array(22);
  const e = new DataView(end.buffer);
  e.setUint32(0, 0x06054b50, true);
  e.setUint16(8, entries.length, true);
  e.setUint16(10, entries.length, true);
  e.setUint32(12, centralBytes, true);
  e.setUint32(16, localOffset, true);
  chunks.push(end);
  return new Blob(chunks, { type: "application/zip" });
}
